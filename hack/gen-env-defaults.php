<?php
/**
 * Generates charts/appwrite/files/env-defaults.yaml from Appwrite's
 * app/config/variables.php.
 *
 * Usage: php hack/gen-env-defaults.php <path-to-variables.php> <appwrite-version> > charts/appwrite/files/env-defaults.yaml
 *
 * The Docker installer writes every variable from variables.php into .env, so
 * Appwrite containers always see those defaults. Code-level fallbacks
 * sometimes differ (for example _APP_SMTP_HOST falls back to "smtp" in code
 * but "" in the installer), so the chart ships the installer defaults to get
 * the same behaviour as a Docker install.
 *
 * Deprecated variables, secrets and variables that only configure Docker
 * (host ports, InfluxDB/StatsD) are left out: the chart manages secrets
 * separately and computes cluster-specific values itself.
 */

namespace Utopia\Config {
    // variables.php only uses Config to build descriptions.
    class Config
    {
        public static function getParam(string $key, mixed $default = []): mixed
        {
            return [];
        }
    }
}

namespace {
    if ($argc < 3) {
        fwrite(STDERR, "usage: php {$argv[0]} <variables.php> <appwrite-version>\n");
        exit(2);
    }

    $categories = require $argv[1];
    $version = $argv[2];

    // Secrets and connection strings that may embed credentials. The chart
    // passes these through Kubernetes Secrets instead.
    $secretPattern = '/(PASS|PASSWORD|SECRET|PRIVATE_KEY|OPENSSL_KEY|ACCESS_KEY|API_KEY)/';
    $secretNames = [
        '_APP_SMS_PROVIDER',
        '_APP_LOGGING_CONFIG',
        '_APP_PWNED_PASSWORDS_DSN',
        '_APP_CONNECTIONS_DB_USAGE',
        '_APP_CONNECTIONS_DB_EXECUTIONS',
        '_APP_CONNECTIONS_DATABASE_DOCUMENTSDB',
        '_APP_CONNECTIONS_DATABASE_VECTORSDB',
        '_APP_EXECUTOR_CONNECTION_STORAGE',
    ];
    // Only meaningful to Docker Compose or unused by Appwrite.
    $skipNames = [
        '_APP_MQTT_PORT',
        '_APP_MQTT_WSS_PORT',
        '_APP_INFLUXDB_HOST',
        '_APP_INFLUXDB_PORT',
        '_APP_STATSD_HOST',
        '_APP_STATSD_PORT',
    ];

    echo "# Generated by hack/gen-env-defaults.php from Appwrite {$version}\n";
    echo "# app/config/variables.php. Do not edit by hand; run `make env-defaults`.\n";
    echo "#\n";
    echo "# These are the defaults the Appwrite Docker installer writes to .env.\n";
    echo "# Values computed by the chart and anything set in appwrite.config\n";
    echo "# take precedence.\n";

    foreach ($categories as $category) {
        $lines = [];
        foreach ($category['variables'] as $variable) {
            $name = $variable['name'];
            if (stripos($variable['description'] ?? '', 'deprecated') !== false) {
                continue;
            }
            if (in_array($name, $skipNames, true) || in_array($name, $secretNames, true)) {
                continue;
            }
            if (preg_match($secretPattern, $name)) {
                continue;
            }
            $lines[] = sprintf('%s: %s', $name, json_encode((string) $variable['default'], JSON_UNESCAPED_SLASHES));
        }
        if ($lines === []) {
            continue;
        }
        echo "\n# {$category['category']}\n";
        echo implode("\n", $lines), "\n";
    }
}
